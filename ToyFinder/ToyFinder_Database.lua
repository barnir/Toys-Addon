-- Função de consulta rápida (entradas manuais primeiro, depois a MassDB gerada)
function ToyFinderDatabase:GetToyData(itemID)
    if not itemID then return nil end
    local e = self.Entries and self.Entries[itemID]
    if e then return e end
    local m = self.MassDB and self.MassDB[itemID]
    if m then
        -- Expande os campos compactos (n/t/s/z/g) para o formato completo usado pelo Core/UI
        return {
            name = m.n,
            sourceType = m.t,
            sourceText = m.s,
            zone = m.z,
            target = m.g,
            cost = m.c,
        }
    end
    return nil
end
